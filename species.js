const speciesGrid =
    document.getElementById("speciesGrid");

const searchInput =
    document.getElementById("searchInput");

const filterButtons =
    document.querySelectorAll("#categoryFilters button");

const typeFilters =
    document.getElementById("typeFilters");


let selectedCategory = "All";
let selectedType = "All";

const mainCategories = [
    "Birds",
    "Mammals",
    "Reptiles",
    "Amphibians",
    "Insects",
    "Arachnids",
    "Plants"
];


// ==================================================
// Display Species
// ==================================================

function displaySpecies(species) {

    if (!speciesGrid) return;

    speciesGrid.innerHTML = "";

    species.forEach(item => {

        const card =
            document.createElement("a");

        card.className = "species-card";

        card.href =
            `species-detail.html?id=${item.id}`;

        card.innerHTML = `
            <div class="species-photo">
                ${
                    item.photo && item.photo.length > 0
                    ? `<img src="${item.photo[0]}" alt="${item.name}">`
                    : `<span>Species photograph</span>`
                }
            </div>

            <div class="species-card-content">

                <p class="small-title">
                    ${item.category}
                </p>

                <h3>${item.name}</h3>

                <p class="scientific-name">
                    ${item.scientificName}
                </p>

            </div>
        `;

        speciesGrid.appendChild(card);
    });
}


// ==================================================
// Category
// ==================================================

function matchesSelectedCategory(item) {

    if (selectedCategory === "All") {
        return true;
    }

    if (selectedCategory === "Other") {
        return !mainCategories.includes(item.category);
    }

    return item.category === selectedCategory;
}


// ==================================================
// Filter Species
// ==================================================

function filterSpecies() {

    const searchTerm =
        searchInput
            ? searchInput.value.toLowerCase()
            : "";

    const filtered =
        speciesData.filter(item => {

            const matchesSearch =
                item.name
                    .toLowerCase()
                    .includes(searchTerm) ||

                item.scientificName
                    .toLowerCase()
                    .includes(searchTerm) ||

                (
                    item.type &&
                    item.type
                        .toLowerCase()
                        .includes(searchTerm)
                );


            const matchesCategory =
                matchesSelectedCategory(item);


            const matchesType =
                selectedType === "All" ||
                item.type === selectedType;


            return (
                matchesSearch &&
                matchesCategory &&
                matchesType
            );

        });


    displaySpecies(filtered);
}


// ==================================================
// Search
// ==================================================

if (searchInput) {

    searchInput.addEventListener(
        "input",
        filterSpecies
    );

}


// ==================================================
// Category Buttons
// ==================================================

filterButtons.forEach(button => {

    button.addEventListener(
        "click",
        function () {

            filterButtons.forEach(btn => {
                btn.classList.remove("active");
            });

            this.classList.add("active");

            selectedCategory =
                this.dataset.category;

            selectedType = "All";

            updateTypeFilters();

            filterSpecies();

        }
    );

});


// ==================================================
// Type Filters
// ==================================================

function updateTypeFilters() {

    if (!typeFilters) return;

    typeFilters.innerHTML = "";


    const filteredForTypes =
        speciesData.filter(item => {

            return matchesSelectedCategory(item);

        });


    const types = [
        ...new Set(
            filteredForTypes
                .map(item => item.type)
                .filter(Boolean)
        )
    ];


    if (types.length === 0) {

        typeFilters.style.display =
            "none";

        return;
    }


    typeFilters.style.display =
        "flex";


    const allButton =
        document.createElement("button");

    allButton.textContent =
        selectedCategory === "All"
            ? "All Types"
            : `All ${selectedCategory}`;

    allButton.classList.add("active");


    allButton.addEventListener(
        "click",
        function () {

            selectedType = "All";

            typeFilters
                .querySelectorAll("button")
                .forEach(btn => {
                    btn.classList.remove("active");
                });

            this.classList.add("active");

            filterSpecies();

        }
    );


    typeFilters.appendChild(allButton);


    types.forEach(type => {

        const button =
            document.createElement("button");

        button.textContent =
            type;


        button.addEventListener(
            "click",
            function () {

                selectedType =
                    type;

                typeFilters
                    .querySelectorAll("button")
                    .forEach(btn => {
                        btn.classList.remove("active");
                    });

                this.classList.add("active");

                filterSpecies();

            }
        );


        typeFilters.appendChild(button);

    });

}


