// ==================================================
// Update Carousel
// ==================================================

function updatePhoto() {

    if (!selectedDetailSpecies) return;

    if (
        !selectedDetailSpecies.photo ||
        selectedDetailSpecies.photo.length === 0
    ) {
        return;
    }


    const photoElement =
        document.getElementById("speciesPhoto");

    const photoCounter =
        document.getElementById("photoCounter");


    if (!photoElement) return;


    photoElement.src =
        selectedDetailSpecies.photo[
            currentPhotoIndex
        ];

    photoElement.alt =
        selectedDetailSpecies.name;


    if (photoCounter) {

        photoCounter.textContent =
            `${currentPhotoIndex + 1} / ${selectedDetailSpecies.photo.length}`;

    }

}


// ==================================================
// Previous Photo
// ==================================================

function prevPhoto() {

    if (!selectedDetailSpecies) return;

    if (
        !selectedDetailSpecies.photo ||
        selectedDetailSpecies.photo.length === 0
    ) {
        return;
    }


    currentPhotoIndex--;


    if (currentPhotoIndex < 0) {

        currentPhotoIndex =
            selectedDetailSpecies.photo.length - 1;

    }


    updatePhoto();

}


// ==================================================
// Next Photo
// ==================================================

function nextPhoto() {

    if (!selectedDetailSpecies) return;

    if (
        !selectedDetailSpecies.photo ||
        selectedDetailSpecies.photo.length === 0
    ) {
        return;
    }


    currentPhotoIndex++;


    if (
        currentPhotoIndex >=
        selectedDetailSpecies.photo.length
    ) {

        currentPhotoIndex = 0;

    }


    updatePhoto();

}


